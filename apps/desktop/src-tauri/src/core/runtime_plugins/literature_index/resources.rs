#[derive(Clone)]
pub(crate) struct IndexResources(BTreeMap<IndexSql, String>);
impl IndexResources {
    pub(crate) fn load(
        catalog: &RuntimePluginCatalog,
        package: &RuntimePluginPackage,
    ) -> Result<Self, RuntimePluginError> {
        let mut resources = BTreeMap::new();
        for (key, file, hash) in SPECS {
            resources.insert(
                *key,
                data::load_text(catalog, package, "literature_library", file, hash)?,
            );
        }
        Ok(Self(resources))
    }
    pub(super) fn sql(&self, key: IndexSql) -> &str {
        self.0
            .get(&key)
            .expect("all finite index resources loaded together")
    }
}
