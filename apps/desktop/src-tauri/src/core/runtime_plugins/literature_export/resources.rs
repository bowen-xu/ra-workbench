pub(crate) struct ResearchExportSql {
    pub(super) statements: Vec<(&'static str, String)>,
}
impl ResearchExportSql {
    pub(crate) fn load(
        catalog: &RuntimePluginCatalog,
        package: &RuntimePluginPackage,
    ) -> Result<Self, RuntimePluginError> {
        let statements = ASSETS
            .iter()
            .map(|&(name, file, hash)| {
                data::load_text(
                    catalog,
                    package,
                    "literature_library",
                    &format!("data/{file}"),
                    hash,
                )
                .map(|sql| (name, sql))
            })
            .collect::<Result<Vec<_>, _>>()?;
        Ok(Self { statements })
    }
}
