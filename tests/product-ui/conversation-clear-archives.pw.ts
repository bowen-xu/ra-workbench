import { expect, test } from "@playwright/test";

test("the app archive toolbar confirms every clear and preserves current conversations", async ({ page }) => {
  test.setTimeout(60_000);
  await page.goto("/?preview=app");
  await page.getByRole("button", { name: "打开对话", exact: true }).click();
  const input = page.getByRole("textbox", { name: "给研究助手发送消息", exact: true });
  await input.fill("Archive clear test"); await input.press("Enter");
  await expect(page.getByRole("button", { name: "停止生成", exact: true })).toHaveCount(0);
  await expect(page.locator(".writing-agent-message.assistant")).toHaveCount(1);
  await expect(page.getByRole("button", { name: "停止生成", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "对话列表", exact: true }).click();
  const drawer = page.getByRole("complementary", { name: "对话列表面板" });
  const rows = drawer.locator("[data-conversation-id]");
  const initialCount = await rows.count();
  const selected = rows.filter({ has: page.locator('button[aria-current="true"]') });
  await selected.hover();
  await selected.getByRole("button", { name: "归档对话", exact: true }).click();
  await expect(rows).toHaveCount(initialCount - 1);
  await drawer.getByRole("button", { name: "新对话", exact: true }).click();
  await input.fill("Current conversation stays"); await input.press("Enter");
  await expect(page.locator(".writing-agent-message.assistant")).toHaveCount(1);
  await expect(page.getByRole("button", { name: "停止生成", exact: true })).toHaveCount(0);
  await expect(rows).toHaveCount(initialCount);
  const currentIds = await rows.evaluateAll(nodes => nodes.map(node => node.getAttribute("data-conversation-id")));
  await drawer.getByRole("button", { name: "查看归档对话", exact: true }).click();
  await expect(rows).toHaveCount(1);
  const trigger = drawer.getByRole("button", { name: "清空归档", exact: true });
  await trigger.click();
  const modal = page.getByRole("dialog", { name: "清空归档对话", exact: true });
  await expect(modal).toContainText("1 个已归档对话");
  await expect(modal.getByRole("button", { name: "取消", exact: true })).toBeFocused();
  await expect(modal.getByRole("checkbox")).toHaveCount(0);
  await expect(rows).toHaveCount(1);
  await page.screenshot({ path: ".tmp/conversation-clear-archive-confirmation.png" });
  await page.keyboard.press("Escape");
  await expect(modal).toHaveCount(0); await expect(trigger).toBeFocused();
  await trigger.click();
  await modal.getByRole("button", { name: "清空归档", exact: true }).click();
  await expect(modal).toHaveCount(0); await expect(rows).toHaveCount(0);
  await expect(trigger).toBeDisabled();
  await drawer.getByRole("button", { name: "返回当前对话", exact: true }).click();
  await expect(rows).toHaveCount(currentIds.length);
  expect(await rows.evaluateAll(nodes => nodes.map(node => node.getAttribute("data-conversation-id")))).toEqual(currentIds);
});

test("bulk clearing in the deletion preview covers archives outside the search results", async ({ page }) => {
  await page.goto("/?demo=conversation-delete");
  const rows = page.locator(".conversation-list-row");
  await expect(rows).toHaveCount(3);
  await page.getByRole("button", { name: "搜索对话", exact: true }).click();
  const search = page.getByRole("searchbox");
  await search.fill("__no_match__"); await search.press("Enter");
  await expect(rows).toHaveCount(0);
  await page.getByRole("button", { name: "清空归档", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "清空归档对话", exact: true });
  await expect(modal).toContainText("3 个已归档对话");
  await modal.getByRole("button", { name: "清空归档", exact: true }).click();
  await expect(modal).toHaveCount(0);
  await search.press("Escape");
  await expect(rows).toHaveCount(0);
  await expect(page.getByRole("button", { name: "清空归档", exact: true })).toBeDisabled();
});
