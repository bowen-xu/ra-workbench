import { expect, test } from "@playwright/test";
import {openToolHistory, openWritingJournal, setToolDeveloperMode} from "./tool-journal";

test("tool raw-data actions stay on the header line without toggling its disclosure", async ({ page }) => {
  for (const width of [1172, 632]) {
    await page.setViewportSize({ width, height: 808 });
    await openToolHistory(page);
    await page.locator('.writing-agent-turn-process > summary').first().click();
    const group = page.locator('.writing-agent-activity-group').first();
    await group.locator(':scope > summary').click();
    const record = group.locator('.tool-history-row').first();
    const height = (await record.boundingBox())!.height;
    await setToolDeveloperMode(page,true);
    const raw = record.getByRole('button', { name: '查看原始数据', exact: true });
    const header = record.locator(':scope > summary');
    const buttonBounds = (await raw.boundingBox())!, headerBounds = (await header.boundingBox())!;
    expect((await record.boundingBox())!.height).toBe(height);
    expect(buttonBounds.y).toBeGreaterThanOrEqual(headerBounds.y);
    expect(buttonBounds.y + buttonBounds.height).toBeLessThanOrEqual(headerBounds.y + headerBounds.height);
    expect(buttonBounds.x + buttonBounds.width).toBe(headerBounds.x + headerBounds.width);
    await expect(record.locator('.writing-agent-activity-actions .agent-message-data-trigger')).toHaveCount(0);
    await expect(record).not.toHaveAttribute('open', '');
    await raw.click();
    const inline = record.locator('..').getByLabel('消息原始数据', {exact:true});
    await expect(inline).toContainText('exec_command');
    await expect(inline).toHaveCSS('user-select', 'text');
    await expect(page.getByRole('dialog', { name: '消息原始数据', exact: true })).toHaveCount(0);
    await expect(record).not.toHaveAttribute('open', '');
    await expect(raw).toBeFocused();
    await page.screenshot({ path: `.tmp/developer-tool-header-${width}.png`, fullPage: true });
    await header.click();
    await expect(record).toHaveAttribute('open', '');
    await expect(inline).toBeVisible();
    await raw.click();
    await expect(inline).toHaveCount(0);
    await expect(record).toHaveAttribute('open', '');
    await setToolDeveloperMode(page,false);
  }
});

test("developer mode persists across settings and App reload and inspects per-message records", async ({ page, context }) => {
  await openWritingJournal(page);
  await expect(page.getByRole('button', { name: '查看原始数据', exact: true })).toHaveCount(0);
  await setToolDeveloperMode(page,true);
  const user = page.locator('.writing-agent-message.user').first();
  await user.hover();
  const raw = user.getByRole('button', { name: '查看原始数据', exact: true });
  const copy = user.getByRole('button', { name: '复制消息', exact: true });
  expect(await raw.innerText()).toBe('');
  expect(await raw.evaluate(button => button.nextElementSibling?.getAttribute('aria-label'))).toBe('复制消息');
  const rawBox = (await raw.boundingBox())!, copyBox = (await copy.boundingBox())!;
  expect(rawBox.y).toBe(copyBox.y);
  expect(rawBox.x + rawBox.width).toBeLessThanOrEqual(copyBox.x);
  await user.getByRole('button', { name: '查看原始数据' }).click();
  const dialog = page.getByRole('dialog', { name: '消息原始数据', exact: true });
  await expect(dialog.locator('pre')).toContainText('itemStarted');
  await expect(dialog.locator('pre')).toContainText('帮我完善摘要部分');
  const data = JSON.parse(await dialog.locator('pre').innerText());
  expect(data.record.itemId).toBe(data.message.itemId);
  expect(data.record.events.every((event: { conversationId: string }) => event.conversationId === data.record.conversationId)).toBe(true);
  await expect(dialog.locator('pre')).toHaveCSS('user-select', 'text');
  await expect(dialog.getByRole('button', { name: '关闭', exact: true })).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
  await expect(dialog.locator('pre')).toHaveCSS('overflow-y', 'auto');
  await page.screenshot({ path: '.tmp/developer-mode-dialog-refined.png' });
  await page.setViewportSize({ width: 632, height: 808 });
  const bounds = (await dialog.boundingBox())!;
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(632);
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(808);
  await expect(dialog.getByRole('button', { name: '关闭', exact: true })).toBeInViewport();
  await expect(dialog.getByRole('button', { name: '复制消息', exact: true })).toBeInViewport();
  await page.screenshot({ path: '.tmp/developer-mode-dialog-refined-narrow.png' });
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await dialog.getByRole('button', { name: '复制消息', exact: true }).click();
  await expect(dialog.getByRole('button', { name: '已复制消息', exact: true })).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(await dialog.locator('pre').innerText());
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0);
  await expect(user.getByRole('button', { name: '查看原始数据' })).toBeFocused();
  await user.getByRole('button', { name: '查看原始数据' }).click();
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(user.getByRole('button', { name: '查看原始数据' })).toBeFocused();
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByRole('button', {name:/^(隐藏对话|隐藏 AI 写作助手)$/u}).click();
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '高级', exact: true }).click();
  await expect(page.getByRole('switch', { name: '开发者模式', exact: true })).toBeChecked();
  await page.reload();
  await expect(page.getByRole('switch', { name: '开发者模式', exact: true })).toBeChecked();
  await page.getByRole('switch', { name: '开发者模式', exact: true }).uncheck();
  await page.getByRole('button', { name: '打开对话', exact: true }).click();
  await expect(page.getByRole('button', { name: '查看原始数据' })).toHaveCount(0);

});

test("new submissions expose their frozen data even after editing the draft", async ({ page }) => {
  const input = await openWritingJournal(page,true,true);
  await input.fill('原始发送内容🧪');
  await page.getByRole('button',{name:'发送消息',exact:true}).click();
  await expect(page.locator('.writing-agent-turn')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'停止生成',exact:true})).toHaveCount(0);
  const user = page.locator('.writing-agent-message.user').filter({ hasText: '原始发送内容🧪' });
  await expect(user).toHaveCount(1);
  await input.fill('之后修改的草稿');
  await user.hover();
  await user.getByRole('button', { name: '查看原始数据' }).click();
  const dialog = page.getByRole('dialog', { name: '消息原始数据', exact: true });
  await expect(dialog.locator('pre')).toContainText('frozenSubmission');
  const data = JSON.parse(await dialog.locator('pre').innerText());
  expect(data.record.frozenSubmission.input.text).toBe('原始发送内容🧪');
  expect(data.record.frozenSubmission.input.context[0].text).toContain('documentclass');
  expect(await dialog.locator('pre').innerText()).not.toContain('之后修改的草稿');
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(input).toHaveValue('之后修改的草稿');
});
