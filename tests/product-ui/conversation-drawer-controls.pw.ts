import {expect, test} from "@playwright/test";

for (const route of ["app", "agent-canvas", "writing-editor-diff"]) {
  test(`${route} shares conversation drawer search and archive controls`, async ({page}) => {
    await page.goto(`/?demo=${route}`);
    if (route === "app") await page.getByRole("button", {name: "打开对话", exact: true}).click();
    const chatHeader = page.locator(".writing-agent-panel:visible .writing-agent-header");
    await chatHeader.getByRole("button", {name: "对话列表", exact: true}).click();
    const drawer = page.getByRole("complementary", {name: "对话列表面板"});
    const header = drawer.locator("header");
    const order = () => header.locator("button").evaluateAll(buttons => buttons.map(button => button.getAttribute("aria-label")));
    await expect(drawer).toHaveCSS("width", "220px");
    await expect(header.locator("strong")).toHaveCount(0);
    await expect(drawer.getByRole("group", {name: "对话状态"})).toHaveCount(0);
    expect(await order()).toEqual(["内部对话", "查看归档对话", "搜索对话", "隐藏对话列表"]);
    await expect(drawer.getByRole("searchbox")).toHaveCount(0);
    const create = drawer.getByRole("button", {name: "新对话", exact: true});
    expect(await create.locator("svg").getAttribute("class")).toBe(await chatHeader.getByRole("button", {name: "新建会话", exact: true}).locator("svg").getAttribute("class"));
    const rows = drawer.locator("[data-conversation-id]");
    await expect(rows.first()).toBeVisible();
    const count = await rows.count();
    const search = header.getByRole("button", {name: "搜索对话", exact: true});
    await search.click();
    const input = drawer.getByRole("searchbox");
    await expect(input).toBeFocused();
    await input.fill("__missing_conversation__");
    await input.press("Enter");
    await expect(rows).toHaveCount(0);
    await input.press("Escape");
    await expect(input).toHaveCount(0);
    await expect(search).toBeFocused();
    await expect(rows).toHaveCount(count);
    await header.getByRole("button", {name: "查看归档对话", exact: true}).click();
    expect(await order()).toEqual(["返回当前对话", "清空归档", "搜索对话", "隐藏对话列表"]);
    await expect(create).toHaveCount(0);
    const back = header.getByRole("button", {name: "返回当前对话", exact: true});
    await expect(back).toBeFocused();
    const backBox = await back.boundingBox(), drawerBox = await drawer.boundingBox();
    expect(backBox!.x - drawerBox!.x).toBeLessThan(24);
    await back.click();
    await expect(create).toBeVisible();
    await expect(rows).toHaveCount(count);
    await expect(header.getByRole("button", {name: "内部对话", exact: true})).toBeFocused();
    await header.getByRole("button", {name: "内部对话", exact: true}).click();
    await expect(drawer.getByRole("button", {name: "新对话", exact: true})).toHaveCount(0);
    await expect(drawer).toContainText("暂无内部对话");
    await header.getByRole("button", {name: "查看归档对话", exact: true}).click();
    expect(await order()).toEqual(["返回当前对话", "清空归档", "搜索对话", "隐藏对话列表"]);
    await expect(header.locator(".lucide-arrow-left")).toHaveCount(1);
    const internalBack = header.getByRole("button", {name: "返回当前对话", exact: true});
    await expect(internalBack).toBeFocused();
    await drawer.screenshot({path: `.tmp/conversation-drawer-internal-archive-${route}.png`});
    await internalBack.press("Enter");
    await expect(header.getByRole("button", {name: "返回普通对话", exact: true})).toBeFocused();
    await expect(header.locator(".lucide-arrow-left")).toHaveCount(1);
    await header.getByRole("button", {name: "返回普通对话", exact: true}).click();
    await expect(rows).toHaveCount(count);
    await drawer.screenshot({path: `.tmp/conversation-drawer-${route}.png`});
  });
}
