import { expect, test } from "@playwright/test";
import { editorOverlay } from "./editorOverlay";

for (const url of ["/", "/?preview=app"]) {
  test(`writing notes share dollar equation suggestions and insertion on ${url}`, async ({ page }) => {
    await page.goto(url);
    await page.getByRole("button", { name: "写作", exact: true }).click();
    await page.getByRole("button", { name: "新建稿件", exact: true }).click();
    await page.getByRole("dialog", { name: "新建 LaTeX 稿件" }).getByRole("textbox").fill("Writing equation suggestions");
    await page.getByRole("button", { name: "创建稿件", exact: true }).click();
    await page.getByRole("tab", { name: "笔记", exact: true }).click();
    await page.getByRole("button", { name: "新建笔记", exact: true }).click();
    const name = page.getByRole("textbox", { name: "笔记名称", exact: true });
    await name.fill("公式"); await name.press("Enter");
    const surface = page.getByRole("group", { name: "写作笔记正文", exact: true });
    await surface.locator("h1").fill("公式"); await page.keyboard.press("Enter");
    await page.keyboard.type("text $");
    const menu = page.getByRole("listbox");
    await expect(menu.getByRole("option")).toHaveCount(1);
    await expect(menu.getByText("行内公式", { exact: true })).toBeVisible();
    await expect(surface.locator(".inline-equation-preview")).toHaveCount(0);
    await page.screenshot({ path: test.info().outputPath("writing-inline-equation-menu.png"), animations: "disabled" });
    await page.keyboard.press("Tab");
    const inline = page.getByRole("textbox", { name: "行内公式 LaTeX 源码", exact: true });
    await expect(inline).toBeFocused();
    await inline.fill("x^2"); await inline.press("Enter"); await page.keyboard.type("After");
    await expect(surface.locator(".inline-equation-preview")).toHaveCount(1);
    await expect(surface).toContainText("After");
    await expect(surface).not.toContainText("$");
    await page.keyboard.press("Enter"); await page.keyboard.type("$$");
    await expect(menu.getByRole("option")).toHaveCount(1);
    await expect(menu.getByText("公式块", { exact: true })).toBeVisible();
    await page.keyboard.press("Backspace");
    await expect(menu.getByText("行内公式", { exact: true })).toBeVisible();
    await page.keyboard.type("$");
    await expect(menu.getByText("公式块", { exact: true })).toBeVisible();
    await page.keyboard.press("Tab");
    await expect(surface.locator('[data-content-type="formulaBlock"]')).toHaveCount(1);
    await page.getByRole("button", { name: "空公式，点击编辑", exact: true }).click();
    const block = page.getByRole("textbox", { name: "公式 LaTeX 源码", exact: true });
    await block.fill("E=mc^2"); await block.press("Enter");
    await expect(page.locator(".save-state")).toHaveText("已保存");
    await surface.locator('[data-content-type="formulaBlock"]').hover();
    await (await editorOverlay(page, surface)).getByRole("button", { name: "添加块", exact: true }).click();
    await expect(menu).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(menu).toHaveCount(0);
    await expect(surface.locator(".bn-editor p")).toHaveCount(2);
    const text = surface.locator(".bn-editor p").last();
    await page.keyboard.type("$");
    await expect(menu.getByText("行内公式", { exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(menu).toHaveCount(0);
    await expect(text).toHaveText("$");
    await page.keyboard.press("Enter"); await page.keyboard.type("Before$/@");
    await expect(menu).toHaveCount(0);
    await expect(surface).toContainText("Before$/@");
    await page.keyboard.press("Enter"); await page.keyboard.type("/inline equation");
    await expect(menu.getByText("行内公式", { exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(menu).toHaveCount(0);
    await page.keyboard.press("Enter"); await page.keyboard.type("/code");
    await menu.getByText("代码块", { exact: true }).click();
    await page.keyboard.type("$$");
    await expect(menu).toHaveCount(0);
    await expect(surface.locator('[data-content-type="codeBlock"]')).toContainText("$$");
    await expect(surface.locator(".inline-equation-preview")).toHaveCount(1);
    await expect(surface.locator('[data-content-type="formulaBlock"]')).toHaveCount(1);
  });
}
