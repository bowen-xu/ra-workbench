import { expect, test, type Page } from "@playwright/test";
const panel = (page: Page) => page.locator('.writing-agent-panel:visible');
async function newDraft(page: Page) {
  await page.getByRole("button", {name: "打开对话", exact: true}).click();
  const input=page.getByRole("textbox", {name: "给研究助手发送消息", exact: true});
  await expect(input).toBeEnabled();
  await expect(panel(page)).toContainText("研究助手为您服务");
  return input;
}
test("@ defaults to open materials, while Tab and + search the full library", async ({page}) => {
  await page.goto("/?demo=app");
  const title = "Synthetic Research Preview: Evidence and Autonomy";
  await page.getByRole("row", {name: /Synthetic Research Preview/}).dblclick();
  await expect(page.getByText("This PDF is a local sample for frontend interaction testing.", {exact: true})).toBeVisible();
  const input = await newDraft(page);
  const picker = page.getByRole("menu", {name: "选择 Agent 资源"});
  const files = picker.locator(".agent-resource-group-files");
  await input.fill("@");
  await expect(files.getByRole("menuitem")).toHaveCount(5);
  await expect(files).toContainText(title);
  await expect(picker.getByRole("menuitem", {name: "搜索", exact: true})).toBeVisible();
  await expect(picker.getByRole("searchbox")).toHaveCount(0);
  await picker.getByRole("menuitem", {name:"搜索",exact:true}).click();
  await expect(input).toBeFocused();
  await expect(picker.getByRole("searchbox")).toHaveCount(0);
  await expect.poll(() => files.getByRole("menuitem").count()).toBeGreaterThan(5);
  const firstSelected = await files.locator(".is-selected").textContent();
  await input.press("ArrowDown");
  await expect(input).toBeFocused();
  await expect(files.locator(".is-selected")).not.toHaveText(firstSelected!);
  await input.press("ArrowUp");
  await expect(files.locator(".is-selected")).toHaveText(firstSelected!);
  await input.pressSequentially("研究计划");
  await expect(files.getByRole("menuitem")).toHaveCount(1);
  await expect(files).toContainText("研究计划");
  for (let count = 0; count < 4; count += 1) await input.press("Backspace");
  await expect(picker).toHaveCount(0);
  await input.fill("使用 @");
  await picker.getByRole("menuitem", {name:"搜索",exact:true}).click();
  await picker.getByRole("menuitem", {name: "返回已打开的文件", exact: true}).click();
  await expect(input).toBeFocused();
  await expect(files.getByRole("menuitem")).toHaveCount(5);
  await expect(files).toContainText(title);
  await input.press("Escape");
  await page.getByRole("tablist", {name: "打开的标签页"}).getByRole("button", {name: `关闭 ${title}`, exact: true}).click();
  await page.getByRole("button", {name:"打开对话",exact:true}).click();
  await input.fill("@");
  await expect(files.getByRole("menuitem")).toHaveCount(0);
  await picker.getByRole("menuitem", {name:"搜索",exact:true}).click();
  await expect(input).toBeFocused();
  await input.pressSequentially("Vision by Logic");
  await expect(files.getByRole("menuitem", {name:/vision-by-logic.pdf/})).toHaveCount(1);
  await files.getByRole("menuitem", {name:/vision-by-logic.pdf/}).click();
  await expect(input).toBeFocused();
  await expect(input.locator(".agent-composer-reference")).toHaveAttribute("aria-label", /Vision by Logic/);
  await expect(picker).toHaveCount(0);

  await panel(page).getByRole("button", {name: "添加上下文和工具", exact: true}).click();
  const plusMenu = page.getByRole("menu", {name: "添加上下文和工具", exact: true});
  const fileEntry = plusMenu.getByRole("menuitem", {name: "文件", exact: true});
  await fileEntry.focus();
  await expect(plusMenu.getByRole("searchbox")).toHaveCount(0);
  await fileEntry.press("Tab");
  const plusSearch = plusMenu.getByRole("searchbox", {name: "搜索文件"});
  await expect(plusSearch).toBeFocused();
  await plusSearch.fill("研究计划");
  await expect(plusMenu.getByRole("menuitem", {name: /研究计划/})).toBeVisible();
  await plusSearch.press("Escape");
  await expect(plusMenu).toHaveCount(0);
});

test("@ includes the open note and writing project without listing unopened project files", async ({page}) => {
  await page.goto("/?demo=app");
  await page.getByRole("button", {name: "笔记", exact: true}).click();
  await page.getByRole("button", {name: /研究计划（合成笔记）/}).click();
  await expect(page.getByRole("textbox", {name: "笔记标题", exact: true})).toHaveValue("研究计划（合成笔记）");
  const input = await newDraft(page);
  const picker = page.getByRole("menu", {name: "选择 Agent 资源"});
  const files = picker.locator(".agent-resource-group-files");
  await input.fill("@");
  await expect(files.getByRole("menuitem")).toHaveCount(1);
  await expect(files).toContainText("研究计划（合成笔记）");
  await input.press("Escape");
  await expect(picker).toHaveCount(0);
  await panel(page).getByRole("button", {name: "隐藏对话", exact: true}).click();
  await page.getByRole("button", {name: "写作", exact: true}).click();
  await page.getByRole("button", {name: "Autonomy（合成稿件） main.tex", exact: true}).click();
  await expect(page.locator(".writing-workbench")).toBeVisible();
  await page.getByRole("button", {name: "打开对话", exact: true}).click();
  await input.fill("");
  await input.fill("@");
  await expect(files.getByRole("menuitem")).toHaveCount(2);
  await expect(files).toContainText("研究计划（合成笔记）");
  await expect(files).toContainText("Autonomy（合成稿件）");
  await expect(files).not.toContainText("introduction.tex");
  await input.press("Escape");
  await page.getByRole("button", {name: "文献", exact: true}).click();
  await page.getByRole("button", {name:"打开对话",exact:true}).click();
  await input.fill("");
  await input.fill("@");
  await expect(files).toContainText("Autonomy（合成稿件）");
  await picker.screenshot({path: ".tmp/agent-opened-materials.png"});
});
