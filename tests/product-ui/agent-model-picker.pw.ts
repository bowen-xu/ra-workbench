  const modelLink = settings.getByRole("button", { name: "选择模型", exact: true });
  await expect(modelLink).toContainText("Medium");
  await expect(modelLink).toContainText("GPT-5.6 Terra");
  await modelLink.hover();
  expect(await modelLink.evaluate(el => getComputedStyle(el).backgroundColor)).toBe("rgb(240, 243, 239)");
  await expect(effort).toHaveAttribute("aria-valuetext", "Medium");
  await effort.focus();
  await page.keyboard.press("ArrowRight");
  await expect(effort).toHaveAttribute("aria-valuetext", "High");
  await expectOriginalWidth();
  const fast = page.getByRole("button", { name: "Fast mode", exact: true });
  await fast.hover();
  const fastHint = page.getByRole("tooltip", { name: "快速模式 更多用量", exact: true });
  await expect(fastHint).toBeVisible();
  expect(await fastHint.locator(".control-hint-caption").evaluate(el => getComputedStyle(el).fontSize)).toBe(await fastHint.evaluate(el => getComputedStyle(el).getPropertyValue("--ui-font-caption").trim()));
  expect(await fast.evaluate(el => ({ width: getComputedStyle(el).width, radius: getComputedStyle(el).borderRadius }))).toEqual({ width: "24px", radius: "8px" });
  await fast.click();
  await expect(fast).toHaveAttribute("aria-pressed", "true");
  await expect(fast.locator("svg")).toHaveAttribute("fill", "currentColor");
  await expectOriginalWidth();
  await expect(trigger.locator(".agent-model-picker-label .lucide-zap")).toHaveCount(0);
