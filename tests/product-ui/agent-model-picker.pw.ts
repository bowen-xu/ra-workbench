import { expect, test } from "@playwright/test";
import {openLiveAgent, holdLiveAgentOutput} from "./live-agent";

test("outside presses finish model selection before panel resize gestures", async ({ page }) => {
  await page.setViewportSize({ width: 632, height: 808 });
  await page.goto("/?demo=writing-editor-diff");
  await page.getByLabel("模拟模型选择", { exact: true }).selectOption("openai");
  const trigger = page.getByRole("button", { name: "选择 AI 写作模型", exact: true });
  const settings = page.getByRole("dialog", { name: "模型和推理强度", exact: true });
  const panel = page.getByRole("dialog", { name: "AI 写作助手", exact: true });
  await trigger.click();
  await page.getByRole("button", { name: "Fast mode", exact: true }).click();
  const effort = page.getByRole("slider", { name: "选择推理强度", exact: true });
  await effort.focus();
  await page.keyboard.press("ArrowRight");
  await expect(settings).toBeVisible();
  // Non-focusable page background outside the chat must also finish selection.
  await page.mouse.click(8, 400);
  await expect(settings).toBeHidden();
  await expect(trigger).toContainText("High");
  await expect(trigger.locator(".agent-model-picker-label > :first-child")).toHaveClass(/lucide-zap/);
  await expect(trigger).not.toBeFocused();

  await trigger.click();
  await settings.getByRole("button", { name: "选择模型", exact: true }).click();
  const models = page.getByRole("dialog", { name: "选择模型", exact: true });
  await expect(models).toBeVisible();
  await page.mouse.click(8, 400);
  await expect(models).toBeHidden();

  const edge = page.getByRole("separator", { name: "调整 AI 写作助手左边界", exact: true });
  await edge.focus();
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("ArrowRight");
  await panel.scrollIntoViewIfNeeded();
  await trigger.click();
  const bounds = (await panel.boundingBox())!;
  const originalWidth = bounds.width;
  const dragX = bounds.x;
  const dragY = bounds.y + bounds.height / 2;
  // The separator is a keyboard control. Pointer resize uses the panel border.
  // Stay at its outer edge because subpixel hit testing can round the midpoint
  // of this one-pixel border into the transcript child.
  await expect.poll(() => panel.evaluate((el, point) =>
    document.elementFromPoint(point.x, point.y) === el, {x: dragX, y: dragY})).toBe(true);
  await page.mouse.move(dragX, dragY);
  await page.mouse.down();
  // Closure happens on press, even before a captured drag emits a click.
  await expect(settings).toBeHidden();
  await expect(panel).toHaveAttribute("data-width-resizing", "true");
  await page.mouse.move(dragX + 70, dragY, { steps: 8 });
  await page.mouse.up();
  await expect.poll(async () => originalWidth - (await panel.boundingBox())!.width).toBeGreaterThan(40);
  await expect(panel).toBeVisible();

  await trigger.click();
  await expect(settings).toBeVisible();
  await trigger.click();
  await expect(settings).toBeHidden();
  await trigger.click();
  await expect(settings).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(settings).toBeHidden();
  await expect(trigger).toBeFocused();
});

test("a configured model keeps its action hint while disabled during a turn", async ({ page }) => {
  const input = await openLiveAgent(page);
  await holdLiveAgentOutput(page);
  await input.fill("检查运行中模型提示");
  await page.getByRole("button", {name: "发送消息", exact: true}).click();
  await expect(page.getByRole("button", {name: "停止生成", exact: true})).toBeVisible();
  const trigger = page.getByRole("button", { name: "选择研究助手模型", exact: true });
  await expect(trigger).toContainText("模拟文本模型");
  await expect(trigger).toBeDisabled();
  await trigger.scrollIntoViewIfNeeded();
  await page.mouse.move(0, 0);
  await trigger.locator("..").hover();
  await trigger.locator("..").hover({ position: { x: 16, y: 16 } });
  await expect(page.getByRole("tooltip", { name: "选择模型", exact: true })).toBeVisible();
  await expect(page.getByRole("tooltip")).not.toContainText("模拟模型");
});

