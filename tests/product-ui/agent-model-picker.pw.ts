  if (!sliderBounds) throw new Error("Effort slider is missing");
  await page.mouse.move(sliderBounds.x + sliderBounds.width / 2, sliderBounds.y + sliderBounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(sliderBounds.x + sliderBounds.width - 15, sliderBounds.y + sliderBounds.height / 2, { steps: 8 });
  await page.mouse.up();
  await expect(effort).toHaveAttribute("aria-valuetext", "Max");
