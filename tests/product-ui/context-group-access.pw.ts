import {expect, test} from "@playwright/test";

test("group access is a persistent ceiling and restores child preferences", async ({page}) => {
  await page.goto("/?preview=app");
  await page.getByRole("row", {name:/Synthetic Research Preview/}).dblclick();
  await page.getByRole("button", {name:"打开对话",exact:true}).click();
  const settings=page.getByRole("button",{name:"上下文管理",exact:true});
  const dialog=page.getByRole("dialog",{name:"上下文管理",exact:true});
  await settings.click();
  const row=dialog.locator('.context-catalog-item[data-selected="true"]');
  const group=row.getByRole("switch",{name:/文件组权限$/});
  const notes=row.getByRole("switch",{name:/阅读笔记 权限$/});
  const portrait=row.getByRole("switch",{name:/文献画像 权限$/});
  const pdf=row.getByRole("switch",{name:/sample.pdf 权限$/});
  await expect(group).toBeChecked();
  await expect(notes).toBeChecked();
  await expect(portrait).toBeChecked();
  await expect(pdf).toBeDisabled();
  await portrait.uncheck();
  await expect(portrait).toBeEnabled();
  await group.uncheck();
  await expect(notes).not.toBeChecked();
  await expect(notes).toBeDisabled();
  await expect(portrait).toBeDisabled();
  await expect(group).toBeEnabled();
  await page.keyboard.press("Escape");
  await page.reload();
  const launcher=page.getByRole("button",{name:"打开对话",exact:true});
  await expect(settings.or(launcher)).toBeVisible();
  if(await launcher.isVisible()) await launcher.click();
  await settings.click();
  await expect(group).not.toBeChecked();
  await expect(notes).toBeDisabled();
  await group.check();
  await expect(notes).toBeChecked();
  await expect(notes).toBeEnabled();
  await expect(portrait).not.toBeChecked();
  await expect(pdf).not.toBeChecked();
  await expect(pdf).toBeDisabled();
  await dialog.screenshot({path:".tmp/context-group-access.png"});
});
