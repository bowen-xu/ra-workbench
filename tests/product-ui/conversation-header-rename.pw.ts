import { expect, test } from "@playwright/test";

test("chat Tab retains focus without sending and preserves explicit file expansion", async ({page}) => {
  await page.goto("/?demo=app");
  await page.getByRole("button", {name: "打开对话", exact: true}).click();
  const composer = page.getByRole("textbox", {name: "给研究助手发送消息", exact: true});
  await composer.fill("Unsent Tab navigation draft");
  await composer.press("Tab"); await expect(composer).toBeFocused();
  await page.keyboard.press("Shift+Tab"); await expect(composer).toBeFocused();
  await expect(composer).toHaveValue("Unsent Tab navigation draft");
  await expect(page.locator(".writing-agent-panel:visible")).not.toContainText("本轮已读取");
  const settings = page.getByRole("button", {name: "上下文管理", exact: true});
  await settings.focus(); await settings.press("Tab"); await expect(settings).toBeFocused();
  await page.keyboard.press("Shift+Tab"); await expect(settings).toBeFocused();
  await page.getByRole("button", {name: "添加上下文和工具", exact: true}).click();
  const files = page.getByRole("menu", {name: "添加上下文和工具", exact: true}).locator('[aria-label="文件"]');
  await files.focus(); await files.press("Tab");
  await expect(page.getByRole("searchbox", {name: "搜索文件", exact: true})).toBeFocused();
});

test("App header double click renames the selected conversation and preserves its draft", async ({page}) => {
  await page.goto("/?demo=app");
  await page.getByRole("button", {name: "打开对话", exact: true}).click();
  const panel = page.locator(".writing-agent-panel:visible");
  const title = panel.locator("span.writing-agent-header-subtitle");
  await expect(title).toHaveText("新对话");
  await title.dblclick();
  await expect(page.getByRole("dialog", {name: "重命名对话", exact: true})).toHaveCount(0);
  const composer = page.getByRole("textbox", {name: "给研究助手发送消息", exact: true});
  await composer.fill("Header rename example");
  await page.getByRole("button", {name: "发送消息", exact: true}).click();
  await expect(panel).toContainText("本轮已读取 0 项上下文");
  await composer.fill("Keep this unsent draft");
  const originalPosition = await title.boundingBox();
  await title.dblclick();
  const input = panel.getByRole("textbox", {name: "对话名称", exact: true});
  await expect(input).toBeFocused();
  const editingPosition = await input.boundingBox();
  expect(Math.abs(editingPosition!.x - originalPosition!.x)).toBeLessThan(5);
  expect(Math.abs(editingPosition!.y - originalPosition!.y)).toBeLessThan(5);
  await expect(page.getByRole("dialog", {name: "重命名对话", exact: true})).toHaveCount(0);
  await input.fill("研究记录");
  await input.press("Tab");
  await expect(input).toHaveCount(0);
  await expect(title).toHaveText("研究记录");
  await expect(title).toBeFocused();
  await expect(composer).toContainText("Keep this unsent draft");
  await page.getByRole("button", {name: "对话列表", exact: true}).click();
  await expect(page.locator('[data-conversation-id] [aria-current="true"]')).toContainText("研究记录");
  await page.getByRole("button", {name: "隐藏对话列表", exact: true}).click();
  await title.dblclick();
  await input.fill("取消这次修改");
  await page.keyboard.press("Escape");
  await expect(input).toHaveCount(0); await expect(title).toHaveText("研究记录");
  await expect(title).toBeFocused();
  await page.reload();
  await page.getByRole("button", {name: "打开对话", exact: true}).click();
  await expect(title).toHaveText("研究记录");
});

test("configured writing conversations save the inline name on blur", async ({page}) => {
  await page.goto("/?demo=app");
  await page.getByRole("button", {name: "写作", exact: true}).click();
  await page.getByRole("button", {name: "Autonomy（合成稿件） main.tex", exact: true}).click();
  await page.getByRole("button", {name: "打开对话", exact: true}).click();
  await page.getByRole("button", {name: "对话列表", exact: true}).click();
  await page.locator('[aria-label="对话列表面板"] [data-conversation-id]').getByRole("button", {name: "完善摘要", exact: true}).first().click();
  await page.getByRole("button", {name: "隐藏对话列表", exact: true}).click();
  const title = page.locator(".writing-agent-panel:visible span.writing-agent-header-subtitle");
  await expect(title).toHaveText("完善摘要");
  await title.dblclick();
  const input = page.getByRole("textbox", {name: "对话名称", exact: true});
  await input.fill("摘要修改讨论");
  const composer = page.getByRole("textbox", {name: "给 AI 写作助手发送消息", exact: true});
  await composer.click();
  await expect(title).toHaveText("摘要修改讨论");
  await expect(input).toHaveCount(0);
  await expect(composer).toBeFocused();
  await page.getByRole("button", {name: "对话列表", exact: true}).click();
  await expect(page.locator('[data-conversation-id] [aria-current="true"]')).toContainText("摘要修改讨论");
});

