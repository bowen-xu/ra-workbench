import { expect, test } from "@playwright/test";
import { writeFile } from "node:fs/promises";

test("PDF selection dictionary uses bundled ECDICT after the note action without external requests", async ({ page }) => {
  // This full workflow includes initial PDF loading and two complete reloads
  // with request interception; retain the per-assertion timeouts throughout.
  test.setTimeout(60_000);
  const failures: string[] = [], dictionaryRequests: string[] = [];
  const origin = new URL(test.info().project.use.baseURL as string).origin;
  page.on("pageerror", error => failures.push(error.message));
  await page.route("**/*", route => {
    const url = new URL(route.request().url());
    if (url.origin !== origin || /^\/(api|v1|rpc|tauri)(\/|$)/.test(url.pathname)) {
      failures.push(`Unexpected external request: ${url.origin}${url.pathname}`); return route.abort();
    }
    if (url.pathname.startsWith("/dictionary/")) dictionaryRequests.push(url.pathname);
    return route.continue();
  });
  await page.goto("/?demo=app");
  await page.getByRole("row", { name: /Synthetic Research Preview/ }).dblclick();
  const line = page.locator(".pdf-view .textLayer span").filter({ hasText: "This PDF is a local sample for frontend interaction testing." }).first();
  await expect(line).toBeVisible();
  const bounds = await line.evaluate(element => {
    const node = element.firstChild;
    const offset = node?.textContent?.indexOf("local") ?? -1;
    if (!node || offset < 0) throw new Error("Sample word is missing");
    const range = document.createRange(); range.setStart(node, offset); range.setEnd(node, offset + 5);
    const rect = range.getBoundingClientRect();
    return { x: rect.x, y: rect.y, width: rect.width, height: rect.height };
  });
  await page.mouse.dblclick(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  const toolbar = page.getByLabel("选区操作", { exact: true });
  await expect(toolbar).toBeVisible();
  const compactPopup = await page.locator(".reader-selection-popover").boundingBox();
  const lastAction = await toolbar.getByRole("button", { name: "AI 解释", exact: true }).boundingBox();
  if (!compactPopup || !lastAction) throw new Error("Selection toolbar is not positioned");
  const trailingSpace = compactPopup.x + compactPopup.width - lastAction.x - lastAction.width;
  expect(trailingSpace).toBeGreaterThanOrEqual(5);
  expect(trailingSpace).toBeLessThanOrEqual(8);
  const order = await toolbar.locator(".selection-primary-actions button").evaluateAll(buttons => buttons.map(button => button.getAttribute("aria-label")));
  expect(order.indexOf("离线查词")).toBe(order.indexOf("写笔记") + 1);
  expect(dictionaryRequests).toEqual([]);
  const savedCount = await page.locator(".saved-highlight").count();
  await toolbar.getByRole("button", { name: "离线查词", exact: true }).click();
  const dictionary = page.getByRole("region", { name: "离线词典", exact: true });
  await expect(dictionary).toBeVisible();
  await expect(dictionary.getByRole("textbox")).toHaveCount(0);
  await expect(dictionary.getByRole("button", { name: "查词", exact: true })).toHaveCount(0);
  await expect(dictionary.locator("article strong").first()).toHaveText("local");
  await expect(dictionary.locator("footer")).toHaveCount(0);
  const explanation = dictionary.getByLabel("AI 语境释义", { exact: true });
  await expect(explanation).toHaveCount(0);
  await expect(toolbar.getByRole("button", { name: "AI 解释", exact: true })).toHaveCount(0);
  await toolbar.getByRole("button", { name: "AI 语境释义", exact: true }).click();
  await expect(explanation.locator(".dictionary-context-translation")).toHaveText("本地的");
  const translationLayout = await explanation.locator(".dictionary-context-translation").evaluate(element => ({
    height: element.getBoundingClientRect().height, lineHeight: Number.parseFloat(getComputedStyle(element).lineHeight),
  }));
  expect(translationLayout.height).toBeLessThanOrEqual(translationLayout.lineHeight + 1);
  await expect(explanation.locator(".dictionary-context-reason")).toContainText("“local”");
  await expect(explanation).not.toContainText("fixture-generation");
  const deleteMeaning = explanation.getByRole("button", { name: "删除词义解释", exact: true });
  await page.mouse.move(20, 20);
  await expect(deleteMeaning).toHaveCSS("opacity", "0");
  await explanation.hover();
  await expect(deleteMeaning).toHaveCSS("opacity", "1");
  await page.mouse.move(20, 20);
  await expect(deleteMeaning).toHaveCSS("opacity", "0");
  await deleteMeaning.focus();
  await expect(deleteMeaning).toHaveCSS("opacity", "1");
  await explanation.getByRole("button", { name: "继续追问词义", exact: true }).click();
  const localChat = explanation.getByRole("region", { name: "词义局部追问", exact: true });
  await localChat.getByRole("textbox", { name: "词义追问", exact: true }).fill("为什么是这个意思？");
  await localChat.getByRole("button", { name: "发送追问", exact: true }).click();
  await expect(localChat.getByRole("log")).toContainText("模拟回答：关于“local”");
  await expect(page.getByRole("button", { name: "打开对话", exact: true })).toBeVisible();
  await localChat.getByRole("button", { name: "收起局部追问", exact: true }).click();
  await expect(localChat).toHaveCount(0);
  const response = await page.request.get("/dictionary/ecdict-v2/manifest.json");
  const manifest = await response.json() as { entryCount: number; primaryEntryCount: number; fallbackEntryCount: number };
  expect(manifest.entryCount).toBe(3403176); expect(manifest.primaryEntryCount).toBe(3402564); expect(manifest.fallbackEntryCount).toBe(612);
  expect(await page.locator(".saved-highlight").count()).toBe(savedCount);
  expect(dictionaryRequests.some(path => path.endsWith("manifest.json"))).toBe(true);
  expect(dictionaryRequests.filter(path => path.endsWith(".json")).length).toBeLessThan(12);
  const popup = await page.locator(".reader-selection-popover").boundingBox();
  expect(popup?.width).toBeLessThanOrEqual(380);
  expect(popup?.x).toBeGreaterThanOrEqual(0);
  expect((popup?.x ?? 0) + (popup?.width ?? 0)).toBeLessThanOrEqual(1280);
  await page.screenshot({ path: ".tmp/verification/pdf-dictionary-browser.png" });
  await toolbar.getByRole("button", { name: "离线查词", exact: true }).click();
  await expect(dictionary).toHaveCount(0); await expect(toolbar).toBeVisible();
  const marker = page.getByRole("button", { name: "查看“local”的词义解释", exact: true });
  await expect(marker).toBeVisible();
  const markBounds = await marker.boundingBox(); if (!markBounds) throw new Error("Stored word mark has no geometry");
  const mousePoint = { x: markBounds.x + markBounds.width / 2, y: markBounds.y + markBounds.height / 2 };
  await page.mouse.click(mousePoint.x, mousePoint.y);
  const wordPopup = page.locator(".word-explanation-popover");
  await expect(wordPopup).toHaveCount(0);
  await expect(page.getByRole("tooltip")).toHaveCount(0);
  await page.mouse.click(mousePoint.x, mousePoint.y, { button: "right" });
  const view = wordPopup.getByRole("button", { name: "查看词义解释", exact: true });
  await expect(view).toBeVisible();
  const viewBounds = await view.boundingBox(); if (!viewBounds) throw new Error("Explanation action has no geometry");
  expect(Math.abs(viewBounds.x + viewBounds.width / 2 - mousePoint.x)).toBeLessThanOrEqual(1);
  await expect(wordPopup.getByRole("button", { name: "写笔记", exact: true })).toBeVisible();
  await page.mouse.move(mousePoint.x - 80, mousePoint.y);
  await view.hover();
  const hint = page.getByRole("tooltip").filter({ hasText: "查看词义解释" });
  await expect(hint.getByRole("img", { name: "鼠标左键" })).toBeVisible();
  await expect(hint).not.toContainText("左击");
  await view.click(); await expect(wordPopup.locator(".dictionary-context-translation")).toHaveText("本地的");
  await wordPopup.getByRole("button", { name: "关闭词义解释", exact: true }).click();
  await marker.click({ modifiers: ["Alt"] });
  await expect(wordPopup.locator(".dictionary-context-translation")).toHaveText("本地的");
  await wordPopup.getByRole("button", { name: "关闭词义解释", exact: true }).click();
  await marker.dblclick();
  await toolbar.getByRole("button", { name: "离线查词", exact: true }).click();
  await expect(dictionary.locator(".dictionary-context-translation")).toHaveText("本地的");
  await expect(wordPopup.getByRole("button", { name: "查看词义解释", exact: true })).toHaveCount(0);
  await page.reload();
  await expect(marker).toBeVisible();
  await marker.click({ modifiers: ["Alt"] });
  await expect(wordPopup.locator(".dictionary-context-translation")).toHaveText("本地的");
  expect(await page.locator(".saved-highlight").count()).toBe(savedCount);
  await page.screenshot({ path: ".tmp/verification/dictionary-context-restored-browser.png" });
  const fixture = await page.evaluate(() => {
    const key = Object.keys(localStorage).find(key => key.includes("word-explanations-v1:"));
    return key ? JSON.parse(localStorage.getItem(key) ?? "[]") : [];
  });
  await writeFile(".tmp/verification/word-context-public-fixture.json",JSON.stringify(fixture));
  await wordPopup.getByRole("button", { name: "删除词义解释", exact: true }).click();
  await expect(marker).toHaveCount(0); await page.reload(); await expect(marker).toHaveCount(0);
  await expect(line).toBeVisible();
  await expect(page.locator(".saved-highlight")).toHaveCount(savedCount);
  expect(failures).toEqual([]);
});
