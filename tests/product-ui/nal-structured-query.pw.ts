import { expect,test } from "@playwright/test";
import { copula,editSlot,addBlock } from "./nal-query-editor";

async function start(page:import("@playwright/test").Page){
  await page.goto("/?preview=app");
  await page.getByRole("button",{name:"设置文献查询",exact:true}).click();
  return page.getByRole("dialog",{name:"文献查询设置",exact:true});
}
test("statement starts with the copula and presents unframed block handles and a save switch",async({page})=>{
  const panel=await start(page);
  const expression=panel.getByLabel("条件 1 Narsese 语句",{exact:true});
  await expect(expression).toHaveText("[选择连接符]");
  await expect(panel.getByRole("button",{name:"条件 1 左槽",exact:true})).toHaveCount(0);
  await expect(panel.getByRole("button",{name:/调换关系方向/})).toHaveCount(0);
  await expect(page.getByRole("button",{name:"添加 block：条件 1",exact:true})).toBeVisible();
  await expect(panel.getByRole("button",{name:"新建 statement",exact:true})).toHaveCount(0);
  await expect(page.getByRole("button",{name:"拖动条件 1",exact:true})).toBeVisible();
  expect(await panel.locator(".nal-query-block").evaluate(el=>getComputedStyle(el).borderStyle)).toBe("none");
  await copula(page,1);
  await expect(expression).toHaveText("[选择词项] → [选择词项]");
  await expect(panel.getByRole("button",{name:"查询文献",exact:true})).toBeDisabled();
  await editSlot(page,"条件 1 左槽","变量","x");
  await editSlot(page,"条件 1 右槽","领域");
  await expect(panel.getByRole("button",{name:"移除输出变量 ?x",exact:true})).toHaveAttribute("aria-pressed","true");
  const save=panel.getByRole("switch",{name:"保存为查询集合",exact:true});
  await expect(save).not.toBeChecked();await save.check();
  await expect(panel.getByLabel("查询集合名称",{exact:true})).toBeVisible();
  await save.uncheck();await expect(panel.getByLabel("查询集合名称",{exact:true})).toHaveCount(0);
});

test("recursive slots preserve connectors, shared variables, local cancellation and output selection",async({page})=>{
  const panel=await start(page),left="条件 1 左槽";
  await copula(page,1,"==>（蕴含）");
  await editSlot(page,left,"conjunction（∧）");
  await expect(panel.getByRole("group",{name:`${left} 第 1 项（可拖动排序）`,exact:true})).toBeFocused();
  await editSlot(page,`${left} · 第 1 项`,"statement（语句）");
  await editSlot(page,`${left} · 第 1 项 连接符`,"-->（继承）");
  await editSlot(page,`${left} · 第 1 项 左槽`,"变量","x");
  await editSlot(page,`${left} · 第 1 项 右槽`,"AI领域");
  await editSlot(page,`${left} · 第 2 项`,"变量","x");
  await editSlot(page,"条件 1 右槽","变量","y");
  const expression=panel.getByLabel("条件 1 Narsese 语句",{exact:true});
  await expect(expression).toHaveText("(< ?x → AI领域> ∧ ?x) ⇒ ?y".replace("< ","<"));
  await expect(panel.getByRole("button",{name:"移除输出变量 ?x",exact:true})).toHaveCount(1);
  await expect(panel.getByRole("button",{name:"移除输出变量 ?y",exact:true})).toHaveAttribute("aria-pressed","true");
  await editSlot(page,`${left} connector 1`,"disjunction（∨）");
  await expect(expression).toContainText("∨");await expect(expression).toContainText("AI领域");
  await panel.getByRole("button",{name:"移除输出变量 ?x",exact:true}).click();
  await expect(panel.getByRole("button",{name:"添加输出变量 ?x",exact:true})).toHaveAttribute("aria-pressed","false");
  await panel.getByRole("button",{name:"条件 1 右槽",exact:true}).press("Enter");
  const editor=page.getByRole("menu",{name:"条件 1 右槽",exact:true});
  const input=editor.getByRole("textbox",{name:"条件 1 右槽的变量名",exact:true});
  await input.fill("discarded");await input.press("Escape");
  await expect(editor).toHaveCount(0);await expect(panel).toBeVisible();
  await expect(panel.getByRole("button",{name:"条件 1 右槽",exact:true})).toBeFocused();
  await expect(expression).toContainText("?y");
  await panel.getByRole("button",{name:"添加输出变量 ?x",exact:true}).click();
  await editSlot(page,"条件 1 右槽","变量","z");
  await expect(panel.getByRole("button",{name:"移除输出变量 ?y",exact:true})).toHaveCount(0);
  await expect(panel.getByRole("button",{name:"移除输出变量 ?z",exact:true})).toHaveAttribute("aria-pressed","true");
  await panel.getByRole("switch",{name:"保存为查询集合",exact:true}).check();
  await panel.getByLabel("查询集合名称",{exact:true}).fill("递归语句");
  await panel.getByRole("button",{name:"查询并保存",exact:true}).click();await expect(panel).toHaveCount(0);
  await page.reload();
  await page.getByRole("button",{name:"查询操作：递归语句",exact:true}).click();
  await page.getByRole("menuitem",{name:"编辑查询：递归语句",exact:true}).click();
  const saved=page.getByRole("dialog",{name:"编辑查询集合",exact:true});
  await expect(saved.getByLabel("条件 1 Narsese 语句",{exact:true})).toHaveText("(<?x → AI领域> ∨ ?x) ⇒ ?z");
  await expect(saved.getByRole("button",{name:"移除输出变量 ?z",exact:true})).toHaveAttribute("aria-pressed","true");
});

