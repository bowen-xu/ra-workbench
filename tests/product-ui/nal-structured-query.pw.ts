  await panel.getByRole("button",{name:"移除条件 1",exact:true}).click();
  await panel.getByRole("button",{name:"移除输出变量 ?文章",exact:true}).click();
  await panel.getByRole("switch",{name:"保存为查询集合",exact:true}).check();
