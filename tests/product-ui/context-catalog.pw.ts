import { expect, test } from "@playwright/test";

for (const route of ["?demo=app", "?preview=app"]) test(`${route} manages grouped resources and persists child permissions`, async ({page}) => {
  await page.goto(`/${route}`);
  await page.getByRole("button", {name:"打开对话",exact:true}).click();
  await page.getByRole("button", {name:"上下文管理",exact:true}).click();
  let dialog=page.getByRole("dialog", {name:"上下文管理",exact:true});
  await expect(dialog.getByRole("textbox")).toHaveCount(1);
  await expect(dialog).not.toContainText("可编辑目录");
  await expect(dialog).not.toContainText("持续使用的材料");
  await expect(dialog).not.toContainText("添加持续材料");
  await dialog.getByRole("textbox").fill("Vision by Logic");
  const row=dialog.locator(".context-catalog-item").filter({has:page.getByRole("checkbox",{name:/^使用 Vision by Logic/})});
  await row.getByRole("checkbox",{name:/^使用 Vision by Logic/}).check();
  await expect(row.locator('.context-catalog-parts input[type="checkbox"]:not([role="switch"]):checked')).toHaveCount(6);
  const metadata=row.locator(".context-catalog-parts li").filter({hasText:"元数据"});
  await metadata.getByRole("switch").check();
  await expect(metadata.getByRole("switch")).toBeChecked();
  const pdf=row.locator(".context-catalog-parts li").filter({hasText:"vision-by-logic.pdf"});
  await expect(pdf.getByRole("switch")).toBeDisabled();
  await expect(pdf.getByRole("switch")).not.toBeChecked();
  await pdf.getByRole("checkbox").uncheck();
  await expect(pdf.getByRole("checkbox")).not.toBeChecked();
  await page.screenshot({path:`.tmp/context-catalog-${route.includes("demo")?"demo":"preview"}.png`});
  await page.keyboard.press("Escape");
  await page.getByRole("button",{name:"上下文管理",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"上下文管理",exact:true});
  await expect(dialog.locator(".context-catalog-item[data-selected=true]")).toHaveCount(1);
  await expect(dialog.getByRole("switch",{name:/Vision by Logic.*元数据 权限/})).toBeChecked();
  await page.keyboard.press("Escape");
  const input=page.getByRole("textbox",{name:"给研究助手发送消息",exact:true});
  await input.fill("只使用选中的子项");
  await page.getByRole("button",{name:"发送消息",exact:true}).click();
  await expect(page.locator(".writing-agent-panel:visible")).toContainText("本轮已读取 1 项上下文");
});

test("writing project is one searchable object, with file children and permission-driven host switching",async({page})=>{
  await page.goto("/?demo=app");
  await page.getByRole("button",{name:"打开对话",exact:true}).click();
  await page.getByRole("button",{name:"上下文管理",exact:true}).click();
  let dialog=page.getByRole("dialog",{name:"上下文管理",exact:true});
  await dialog.getByRole("textbox").fill("Autonomy");
  const row=dialog.locator(".context-catalog-item").filter({has:page.getByRole("checkbox",{name:/^使用 Autonomy/})});
  await expect(row).toHaveCount(1);
  await row.getByRole("checkbox",{name:/^使用 Autonomy/}).check();
  // A newly selected project is writable and immediately acquires its host.
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("textbox",{name:"给 AI 写作助手发送消息",exact:true})).toBeEnabled();
  await page.getByRole("button",{name:"上下文管理",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"上下文管理",exact:true});
  await expect(dialog.getByRole("switch",{name:/Autonomy.* · main.tex 权限/})).toBeChecked();
  await expect(dialog.getByRole("switch",{name:/Autonomy.* · sections\/introduction.tex 权限/})).toBeChecked();
  await dialog.getByRole("switch",{name:/Autonomy.* · main.tex 权限/}).click();
  await dialog.getByRole("switch",{name:/Autonomy.*文件组权限$/}).uncheck();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("textbox",{name:"给研究助手发送消息",exact:true})).toBeEnabled();
  await page.getByRole("button",{name:"上下文管理",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"上下文管理",exact:true});
  await expect(dialog.getByRole("switch",{name:/Autonomy.* · main.tex 权限/})).not.toBeChecked();
  await expect(dialog.getByRole("switch",{name:/Autonomy.* · main.tex 权限/})).toBeDisabled();
  await dialog.getByRole("switch",{name:/Autonomy.*文件组权限$/}).check();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("textbox",{name:"给 AI 写作助手发送消息",exact:true})).toBeEnabled();
  await page.getByRole("button",{name:"上下文管理",exact:true}).click();
  await expect(dialog.getByRole("switch",{name:/Autonomy.* · main.tex 权限/})).not.toBeChecked();
  await expect(dialog.getByRole("switch",{name:/Autonomy.* · sections\/introduction.tex 权限/})).toBeChecked();
});
