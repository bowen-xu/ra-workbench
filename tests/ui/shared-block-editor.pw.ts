import { expect, test } from "@playwright/test";

test("two independent editor hosts share editing, not storage, identity or selection state", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await page.evaluate(async () => {
    const { mountSharedEditorFixture } = await import("/src/core/components/block-editor/BlockEditor.fixture.tsx");
    mountSharedEditorFixture();
  });
  const left = page.getByRole("region", { name: "写作思路" });
  const right = page.getByRole("region", { name: "临时草稿" });
  const row = left.locator('.bn-block[data-id="parent"] > .bn-block-content');
  const first = left.locator('.bn-block[data-id="first"] > .bn-block-content');
  await expect(row).toHaveText("Parent");
  await expect(right.locator('.bn-block[data-id="parent"] > .bn-block-content')).toHaveText("Parent");
  await expect(left.locator("output")).toHaveText("");
  const originalDom = await left.locator(".bn-editor").elementHandle();
  await row.hover();
  const owner = await left.locator('[data-editor-instance]').getAttribute("data-editor-instance");
  const handle = page.locator(`[data-editor-overlay-owner="${owner}"]`).getByRole("button", { name: "拖动块；点击打开块菜单" });
  await expect(handle).toHaveAttribute("data-block-id", "parent");
  const from = await handle.boundingBox(); const to = await first.boundingBox();
  if (!from || !to) throw new Error("Missing editor geometry");
  await page.mouse.move(from.x + 16, from.y + 16);
  await page.mouse.down();
  await page.mouse.move(to.x + 4, to.y + 2, { steps: 12 });
  await expect(left.locator('.bn-block-outer[data-id="parent"]').first()).toHaveCSS("background-color", "rgb(234, 242, 237)");
  await expect(right.locator('.bn-block-outer[data-id="parent"]').first()).not.toHaveCSS("background-color", "rgb(234, 242, 237)");
  await page.mouse.up();
  await expect(left.locator(".bn-block-content").first()).toHaveText("Parent");
  await expect(right.locator(".bn-block-content").first()).toHaveText("First");
  await expect(left.locator("output")).toContainText('"outline"');
  await expect(right.locator("output")).toHaveText("");
  await left.getByRole("button", { name: "保存回执", exact: true }).click();
  expect(await originalDom?.evaluate((node) => node.isConnected)).toBe(true);
  // Undo belongs to the editing host, not its save adapter or another editor.
  await left.locator(".bn-editor").focus();
  await page.keyboard.press("ControlOrMeta+z");
  await expect(left.locator(".bn-block-content").first()).toHaveText("First");
  await expect(right.locator("output")).toHaveText("");
  await left.getByRole("button", { name: "切换只读" }).click();
  await expect(left.locator(".bn-editor")).toHaveAttribute("contenteditable", "false");
  await expect(left.getByRole("button", { name: "公式 x^2，只读", exact: true })).toBeDisabled();
  await expect(page.getByRole("textbox", { name: "公式 LaTeX 源码", exact: true })).toHaveCount(0);
  await right.getByRole("button", { name: "公式 x^2，点击编辑", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "公式 LaTeX 源码", exact: true })).toBeEditable();
  await page.getByRole("button", { name: "完成", exact: true }).click();
  const savedOutline = await left.locator("output").textContent();
  await right.locator('.bn-block[data-id="first"] > .bn-block-content').click();
  await page.keyboard.press("End");
  await page.keyboard.type(" scratch");
  await expect(right.locator("output")).toContainText("first,parent,tail,formula");
  await expect(right.locator("output")).not.toContainText('"outline"');
  await expect(left.locator("output")).toHaveText(savedOutline ?? "");
  await page.screenshot({ path: ".tmp/playwright-results/shared-block-editor.png" });
  expect(errors).toEqual([]);
});
